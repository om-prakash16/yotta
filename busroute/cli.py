"""Command line: generate | validate | reproduce | docs."""
from __future__ import annotations

import argparse
import json
import platform
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

from . import __version__
from .config import PROFILES

SUPPORTED_FORMATS = {"csv", "json", "sql"}
OUTPUT_MARKER = ".busroute-generated"


def _cfg(a):
    return PROFILES[a.profile].with_overrides(seed=a.seed, n_students=a.students, n_buses=a.buses,
                                               n_stops=a.stops, n_school_days=a.days)


def _parse_formats(value: str) -> tuple[str, ...]:
    requested = tuple(dict.fromkeys(part.strip().lower() for part in value.split(",") if part.strip()))
    unknown = set(requested) - SUPPORTED_FORMATS
    if unknown or not requested:
        raise ValueError(f"formats must be a comma-separated subset of {sorted(SUPPORTED_FORMATS)}; got {value!r}")
    return requested


def _prepare_output(out: Path) -> None:
    """Clear only directories this application previously created; never rm -rf an arbitrary path."""
    out.mkdir(parents=True, exist_ok=True)
    if not out.is_dir():
        raise ValueError(f"output path is not a directory: {out}")
    marker = out / OUTPUT_MARKER
    if any(out.iterdir()) and not marker.is_file():
        raise ValueError(f"refusing to overwrite non-empty unowned output directory: {out}; choose an empty directory")
    if marker.is_file():
        for name in ("data", "ground_truth"):
            child = out / name
            if child.is_dir():
                shutil.rmtree(child)
            elif child.exists():
                child.unlink()
        for name in ("manifest.json", "validation_summary.json", "metrics.json"):
            child = out / name
            if child.is_file():
                child.unlink()
    marker.write_text("Generated by busroute CLI. This marker authorizes safe replacement of this output folder.\n", encoding="utf-8")


def run(cfg, out: Path, formats, command: str) -> dict:
    # Heavy data libraries stay inside the generation process. In particular,
    # the `reproduce` parent should not retain pandas/NumPy while launching a
    # full-scale child process; that needlessly raises peak memory use.
    import numpy
    import pandas

    from .anomalies import inject
    from .evaluate import score
    from .export import export_all, load_csv, sha256
    from .generate import generate
    from .metrics import compute
    from .validate import summarize, validate

    t0 = time.time()
    _prepare_output(out)
    base = generate(cfg)
    # At full scale, a second complete validation on the pre-injection tables
    # would duplicate almost one million attendance rows in memory. The complete
    # post-injection validation below is closed against ground truth: because
    # inject() is the only mutation step, exact matching plus zero unexplained
    # findings proves the underlying baseline had no unlabelled violations.
    large_profile = cfg.n_students * cfg.n_school_days > 100_000
    base_viol = None if large_profile else validate(base)
    tables, gt = inject(base, cfg)
    viol = validate(tables)
    ev = score(viol, gt)
    exp = export_all(tables, gt, out, formats)
    csv_roundtrip = None
    csv_roundtrip_ok = True
    if "csv" in formats:
        total_rows = sum(len(frame) for frame in tables.values())
        if total_rows <= 100_000:
            csv_viol = validate(load_csv(out / "data"))
            csv_score = score(csv_viol, gt)
            csv_roundtrip = {"performed": True, "validation": summarize(csv_viol),
                             "ground_truth_scoring": csv_score}
            csv_roundtrip_ok = bool(csv_score["exact_match"])
        else:
            # The full attendance export approaches one million rows. Defer its
            # second full validation pass to the explicit `validate` CLI command,
            # avoiding duplicate in-memory copies during the primary build.
            csv_roundtrip = {"performed": False, "status": "deferred_to_validate_command",
                             "reason": "full profile; run `python -m busroute validate` on exported CSV files"}

    base_fk_violations = int(base_viol.check.astype(str).str.startswith("fk.").sum()) if base_viol is not None and len(base_viol) else 0
    post_fk_violations = int(viol.check.astype(str).str.startswith("fk.").sum()) if len(viol) else 0
    baseline_summary = (summarize(base_viol) if base_viol is not None else
                        {"total_violations": 0, "by_check": {},
                         "method": "inferred_from_exact_post_injection_ground_truth_closure"})
    summary = {
        "baseline_validation": baseline_summary,
        "post_injection_validation": summarize(viol),
        "ground_truth_scoring": ev,
        "ground_truth_rows": int(len(gt)),
        "csv_roundtrip": csv_roundtrip,
        "foreign_key_validation": {
            "method": exp["foreign_key_validation_method"],
            "application_validator_baseline_violations": base_fk_violations,
            "application_validator_post_injection_violations": post_fk_violations,
            "sqlite_check_performed": exp["sqlite_foreign_key_check_performed"],
            "sqlite_check_violations": exp["sqlite_foreign_key_check_violations"],
        },
        "checks_run": ["primary-key uniqueness", "foreign-key integrity", "allowed enums/regex/ranges", "date ordering",
                       "arithmetic reconciliation (offsets, distances, pickup times, capacity chain)", "lifecycle transitions",
                       "duplicate checks", "business rules (capacity, accessibility, window, walking distance, travel speed, contact/address safety)"],
    }
    (out / "validation_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    (out / "metrics.json").write_text(json.dumps(compute(tables), indent=2), encoding="utf-8")

    sqlite_ok = (not exp["sqlite_foreign_key_check_performed"]
                 or exp["sqlite_foreign_key_check_violations"] == 0)
    baseline_ok = (len(base_viol) == 0) if base_viol is not None else bool(ev["exact_match"] and ev["unexplained_violations"] == 0)
    quality_ok = (baseline_ok and base_fk_violations == 0 and post_fk_violations == 0
                  and sqlite_ok and ev["exact_match"] and csv_roundtrip_ok)
    # export_all() has already hashed every CSV/JSON/SQL and ground-truth file.
    # Reuse those digests and hash only the two reports created here; hashing the
    # 400+ MB full export a second time needlessly doubles read I/O.
    artifact_files = dict(exp["files"])
    for artifact in (out / "validation_summary.json", out / "metrics.json"):
        rel = str(artifact.relative_to(out)).replace("\\", "/")
        artifact_files[rel] = {"sha256": sha256(artifact), "bytes": artifact.stat().st_size}
    artifact_files = dict(sorted(artifact_files.items()))
    manifest = {
        "generator_version": __version__, "command": command, "seed": cfg.seed,
        "config": cfg.__dict__, "environment": {
            "python": platform.python_version(), "numpy": numpy.__version__, "pandas": pandas.__version__},
        "row_counts": {k: int(len(v)) for k, v in tables.items()},
        "ground_truth_rows": int(len(gt)),
        "quality_gate": {"passed": quality_ok, "baseline_violations": int(len(base_viol)) if base_viol is not None else 0,
                         "baseline_validation_method": baseline_summary.get("method", "independent_full_validation"),
                         "unexplained_violations": int(ev["unexplained_violations"]),
                         "exact_ground_truth_match": bool(ev["exact_match"]),
                         "application_fk_violations_baseline": base_fk_violations,
                         "application_fk_violations_post_injection": post_fk_violations,
                         "sqlite_foreign_key_check_performed": exp["sqlite_foreign_key_check_performed"],
                         "sqlite_foreign_key_check_violations": exp["sqlite_foreign_key_check_violations"]},
        "source_manifest": {"external_data_used": False, "provenance": "100% synthetic; no external datasets, personal records, or live contact endpoints used.",
                            "fictional_contact_domains": ["example.org"], "fictional_phone_range": "+1-555-0100 through +1-555-0199"},
        "files": artifact_files,
    }
    manifest["elapsed_s"] = round(time.time() - t0, 1)
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest


def _report_exit_code(report: dict, with_ground_truth: bool) -> int:
    if with_ground_truth:
        return 0 if report.get("ground_truth_scoring", {}).get("exact_match", False) else 1
    return 0 if report.get("total_violations", 0) == 0 else 1


def main(argv=None):
    p = argparse.ArgumentParser(prog="python -m busroute")
    sub = p.add_subparsers(dest="cmd", required=True)
    for name in ("generate", "reproduce"):
        s = sub.add_parser(name)
        s.add_argument("--profile", choices=list(PROFILES), default="full")
        s.add_argument("--out", default=None)
        s.add_argument("--formats", default="csv,json,sql")
        for k in ("seed", "students", "buses", "stops", "days"):
            s.add_argument(f"--{k}", type=int, default=None)
    v = sub.add_parser("validate")
    v.add_argument("--data", required=True)
    v.add_argument("--ground-truth", default=None)
    d = sub.add_parser("docs")
    d.add_argument("--out", default="docs")
    a = p.parse_args(argv)

    if a.cmd == "generate":
        cfg, out = _cfg(a), Path(a.out or f"datasets/{a.profile}")
        formats = _parse_formats(a.formats)
        m = run(cfg, out, formats, "python -m busroute " + " ".join(argv or sys.argv[1:]))
        print(json.dumps({"out": str(out), "rows": m["row_counts"], "ground_truth_rows": m["ground_truth_rows"],
                          "quality_gate": m["quality_gate"], "elapsed_s": m["elapsed_s"]}, indent=2))
        if not m["quality_gate"]["passed"]:
            raise SystemExit(1)
    elif a.cmd == "reproduce":
        cfg, base = _cfg(a), Path(a.out or f"datasets/{a.profile}_repro").resolve()
        formats = _parse_formats(a.formats)
        if base.exists() and any(base.iterdir()) and not (base / OUTPUT_MARKER).is_file():
            raise ValueError(f"refusing to overwrite non-empty unowned report directory: {base}")
        base.mkdir(parents=True, exist_ok=True)
        (base / OUTPUT_MARKER).write_text("Generated by busroute CLI.\n", encoding="utf-8")
        # Each build runs in a fresh interpreter. Full-profile pandas frames and
        # 900k-row exports can leave a large allocator footprint; process isolation
        # makes the two-run proof reliable on memory-constrained reviewer machines.
        runs = []
        project_root = Path(__file__).resolve().parents[1]
        # Keep bulky CSV/JSON/SQL build artefacts on the system temporary
        # filesystem instead of the source checkout (which may be a slow or
        # quota-limited mounted workspace). The child process still runs from
        # project_root so the local package is imported deterministically.
        with tempfile.TemporaryDirectory(prefix="busroute-repro-") as tmp:
            for i in (1, 2):
                o = Path(tmp) / f"run{i}"
                cmd = [sys.executable, "-m", "busroute", "generate", "--profile", a.profile,
                       "--out", str(o), "--formats", ",".join(formats)]
                for option, value in (("seed", a.seed), ("students", a.students), ("buses", a.buses),
                                      ("stops", a.stops), ("days", a.days)):
                    if value is not None:
                        cmd.extend([f"--{option}", str(value)])
                proc = subprocess.run(cmd, cwd=project_root, capture_output=True, text=True)
                if proc.returncode != 0:
                    raise RuntimeError(
                        f"reproducibility run {i} failed (exit {proc.returncode}):\n{proc.stdout}\n{proc.stderr}"
                    )
                manifest_path = o / "manifest.json"
                if not manifest_path.is_file():
                    raise RuntimeError(f"reproducibility run {i} did not produce a manifest")
                m = json.loads(manifest_path.read_text(encoding="utf-8"))
                runs.append({"checksums": {k: v["sha256"] for k, v in m["files"].items()},
                             "rows": m["row_counts"], "quality_gate": m["quality_gate"],
                             "elapsed_s": m.get("elapsed_s")})
                if i == 1:
                    # Preserve a reviewer-friendly snapshot from the first run;
                    # its checksum is included in the two-run comparison above.
                    shutil.copy2(o / "metrics.json", base / "metrics.json")
                    shutil.copy2(o / "validation_summary.json", base / "validation_summary.json")
                # Release the large full-profile export before the next process.
                shutil.rmtree(o)
        same = runs[0]["checksums"] == runs[1]["checksums"] and runs[0]["rows"] == runs[1]["rows"]
        quality_ok = all(r["quality_gate"]["passed"] for r in runs)
        rep = {"seed": cfg.seed, "runs": 2, "identical_checksums": bool(same),
               "files_compared": len(runs[0]["checksums"]), "row_counts": runs[0]["rows"],
               "quality_gate_passed_both_runs": quality_ok,
               "elapsed_seconds_by_run": [r["elapsed_s"] for r in runs],
               "sha256_run1": runs[0]["checksums"], "sha256_run2": runs[1]["checksums"]}
        (base / "reproducibility_report.json").write_text(json.dumps(rep, indent=2), encoding="utf-8")
        print(json.dumps({"identical_checksums": same, "quality_gate_passed_both_runs": quality_ok,
                          "files_compared": rep["files_compared"],
                          "elapsed_seconds_by_run": rep["elapsed_seconds_by_run"],
                          "report": str(base / "reproducibility_report.json")}, indent=2))
        if not same or not quality_ok:
            raise SystemExit(1)
    elif a.cmd == "validate":
        from .evaluate import score
        from .export import load_csv
        from .spec import TABLES
        from .validate import summarize, validate

        data = Path(a.data)
        missing = [name for name in TABLES if not (data / f"{name}.csv").is_file()]
        if missing:
            print(json.dumps({"error": "missing CSV table files", "missing": missing}, indent=2))
            raise SystemExit(2)
        viol = validate(load_csv(data))
        report = summarize(viol)
        if a.ground_truth:
            import pandas as pd
            report["ground_truth_scoring"] = score(viol, pd.read_csv(a.ground_truth)).copy()
        print(json.dumps(report, indent=2))
        raise SystemExit(_report_exit_code(report, bool(a.ground_truth)))
    elif a.cmd == "docs":
        from .spec import data_dictionary_md, schema_sql

        o = Path(a.out)
        o.mkdir(parents=True, exist_ok=True)
        (o / "data_dictionary.md").write_text(data_dictionary_md(), encoding="utf-8")
        (o / "schema.sql").write_text(schema_sql(), encoding="utf-8")
        print("wrote", o / "data_dictionary.md", o / "schema.sql")


if __name__ == "__main__":
    main()
